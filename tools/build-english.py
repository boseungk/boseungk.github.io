"""Generate English HTML and explicit runtime copy from the Korean homepage."""
from html.parser import HTMLParser
from pathlib import Path
import argparse
import html
import json
import re

ROOT = Path(__file__).resolve().parents[1] / 'docs'
COPY = json.loads((ROOT / 'assets/v5/en-copy.json').read_text())
KOREAN = re.compile('[가-힣]')


class Translate(HTMLParser):
    def __init__(self, copy=None):
        super().__init__(convert_charrefs=False)
        self.output = []
        self.raw = False
        self.copy = COPY if copy is None else copy

    def translate(self, value):
        if KOREAN.search(value) and value != '한국어' and value not in self.copy:
            raise ValueError(f'Missing English copy: {value!r}')
        return self.copy.get(value, value)

    def handle_decl(self, data):
        self.output.append(f'<!{data}>')

    def handle_starttag(self, tag, attrs):
        self.raw = tag in ('script', 'style') or self.raw
        translated = []
        for key, value in attrs:
            if value is not None:
                value = self.translate(value)
            if tag == 'html' and key == 'lang':
                value = 'en'
            translated.append(key if value is None else f'{key}="{html.escape(value, quote=True)}"')
        self.output.append('<' + tag + (' ' + ' '.join(translated) if translated else '') + '>')
        if tag == 'br':
            # Mobile hides description line breaks: retain an English word boundary.
            self.output.append(' ')

    def handle_endtag(self, tag):
        self.output.append(f'</{tag}>')
        if tag in ('script', 'style'):
            self.raw = False

    def handle_data(self, data):
        key = data.strip()
        self.output.append(data if self.raw or not key else data.replace(key, self.translate(key)))

    def handle_entityref(self, name):
        self.output.append(f'&{name};')

    def handle_charref(self, name):
        self.output.append(f'&#{name};')

    def handle_comment(self, data):
        self.output.append(f'<!--{data}-->')


def build_home():
    translator = Translate()
    translator.feed((ROOT / 'index.html').read_text())
    output = ''.join(translator.output)
    output = output.replace('href="/" aria-label="MyAnimalRoom home"', 'href="/en/" aria-label="MyAnimalRoom home"')
    output = output.replace('data-language-current>한국어', 'data-language-current>English')
    output = output.replace('href="/" lang="ko" hreflang="ko" aria-current="page"', 'href="/" lang="ko" hreflang="ko"')
    output = output.replace('href="/en/" lang="en" hreflang="en"', 'href="/en/" lang="en" hreflang="en" aria-current="page"')
    output = output.replace('<link rel="canonical" href="https://www.myanimalroom.com/">', '<link rel="canonical" href="https://www.myanimalroom.com/en/">')
    output = output.replace('property="og:url" content="https://www.myanimalroom.com/"', 'property="og:url" content="https://www.myanimalroom.com/en/"').replace('ko_KR', 'en_US')
    # Validate literal runtime calls as well as native growth recipe labels.
    runtime_keys = set()
    for file in [ROOT / 'home.js', *ROOT.glob('assets/v4/*.js'), *ROOT.glob('assets/v5/*.js')]:
        if file.name == 'copy.js':
            continue
        for key in re.findall(r"MARCopy\.text\('([^']*)'\)", file.read_text()):
            runtime_keys.add(key)
    recipes = (ROOT / 'assets/v5/growth-motion/growth-reveal-recipes.mjs').read_text()
    tree = re.search(r"\{kind:'tree'.*?\},", recipes, re.S)[0]
    for field in ('stages', 'titles'):
        labels = re.search(field + r':\[([^\]]+)\]', tree)[1]
        runtime_keys.update(re.findall(r"'([^']+)'", labels))
    for key in runtime_keys:
        translator.translate(key)
    runtime = '''/* Generated by tools/build-english.py. Translate at the owning controller, never scan the DOM. */
(function (global) {
  'use strict';
  const english = document.documentElement.lang === 'en';
  const copy = __COPY__;
  global.MARCopy = {
    text(value) {
      if (!english) return value;
      if (!Object.hasOwn(copy, value)) throw new Error('Missing English runtime copy: ' + value);
      return copy[value];
    },
    duration(minutes) {
      const hours = Math.floor(minutes / 60), remainder = minutes % 60;
      return english ? `${hours}h ${remainder}m` : `${hours}시간 ${remainder}분`;
    },
    taskSummary(count, total) {
      return english ? (count ? `${count} of ${total} sample tasks completed.` : 'Try marking a sample task complete.')
        : `${count}개 완료 · 체험용 예시로 저장되지 않아요.`;
    }
  };
})(window);
'''.replace('__COPY__', json.dumps({key: COPY[key] for key in sorted(runtime_keys)}, ensure_ascii=False, indent=2))
    return {ROOT / 'en/index.html': output, ROOT / 'assets/v5/copy.js': runtime}


def build_feedback():
    copy = json.loads((ROOT / 'assets/feedback/feedback-copy.json').read_text())
    translator = Translate({**COPY, **copy})
    translator.feed((ROOT / 'feedback/index.html').read_text())
    output = ''.join(translator.output)
    output = output.replace('href="/"', 'href="/en/"').replace('href="/#', 'href="/en/#')
    output = output.replace('data-language-current>한국어', 'data-language-current>English')
    output = output.replace('href="/feedback/" lang="ko" hreflang="ko" aria-current="page"', 'href="/feedback/" lang="ko" hreflang="ko"')
    output = output.replace('href="/en/feedback/" lang="en" hreflang="en"', 'href="/en/feedback/" lang="en" hreflang="en" aria-current="page"')
    output = output.replace('<link rel="canonical" href="https://www.myanimalroom.com/feedback/">', '<link rel="canonical" href="https://www.myanimalroom.com/en/feedback/">')
    output = output.replace('property="og:url" content="https://www.myanimalroom.com/feedback/"', 'property="og:url" content="https://www.myanimalroom.com/en/feedback/"').replace('ko_KR', 'en_US')
    for key in re.findall(r"\bt\('([^']*)'", (ROOT / 'assets/feedback/feedback.js').read_text()):
        translator.translate(key)
        if key not in copy:
            raise ValueError(f'Missing feedback runtime copy: {key!r}')
    runtime = '''// Generated by tools/build-english.py; edit feedback-copy.json.
const english = document.documentElement.lang === 'en';
const copy = __COPY__;
export function text(value, parameters = {}) {
  if (english && !Object.hasOwn(copy, value)) throw new Error('Missing feedback copy: ' + value);
  return (english ? copy[value] : value).replace(/\\{(\\w+)\\}/g, (match, key) => String(parameters[key] ?? match));
}
'''.replace('__COPY__', json.dumps(copy, ensure_ascii=False, indent=2))
    return {ROOT / 'en/feedback/index.html': output, ROOT / 'assets/feedback/copy.mjs': runtime}


def build():
    return {**build_home(), **build_feedback()}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated files are stale')
    args = parser.parse_args()
    for file, content in build().items():
        if args.check:
            if not file.exists() or file.read_text() != content:
                raise SystemExit(f'Stale generated file: {file}')
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content)
    print('PASS English HTML/runtime copy ' + ('reproducibility' if args.check else 'generation'))
